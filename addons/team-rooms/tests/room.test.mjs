import test from 'node:test';
import assert from 'node:assert/strict';
import { roomService } from '../service/server.mjs';
test('private membership, authoritative rolls, concurrency, receipts and expiry', () => {
  let now=0;
  const run=roomService({clock:()=>now});
  const host='a'.repeat(48), guest='b'.repeat(48), stranger='c'.repeat(48);
  const created=run(host,{op:'create'});
  const code=created.code;
  const action=(key,op,args={}) => run(key,{code,round:0,rerolled:false,op,...args});
  assert.equal(run(host,{op:'create'}).code,code);
  assert.throws(()=>action(guest,'join',{code:'0000000000'}),/no_room/);
  assert.throws(()=>action(host,'deal',{tier:1,mask:7}),/waiting/);
  assert.equal(action(guest,'join').players,2);
  assert.throws(()=>action(stranger,'join'),/full/);
  assert.equal(action(stranger,'state'),null);
  assert.throws(()=>action(guest,'deal',{tier:1,mask:7}),/host_only/);
  const first=action(host,'deal',{tier:1,mask:7});
  assert.equal(first.round,1);
  assert.throws(()=>action(host,'deal',{tier:1,mask:7}),/stale/);
  action(host,'reroll',{round:1});
  assert.throws(()=>action(guest,'pick',{round:1,index:0}),/stale/);
  const current=(key,op,args={})=>action(key,op,{round:1,rerolled:true,...args});
  current(host,'pick',{index:1}); current(guest,'pick',{index:2});
  assert.equal(current(host,'pick',{index:1}).choice,1);
  assert.throws(()=>current(host,'reroll'),/locked/);
  assert.throws(()=>current(guest,'finish',{index:0}),/stale/);
  current(host,'finish',{index:1});
  assert.throws(()=>current(host,'deal',{tier:2,mask:5}),/waiting/);
  current(guest,'finish',{index:2});
  assert.equal(current(host,'deal',{tier:2,mask:5}).round,2);
  assert.equal(action(guest,'state').choice,null);
  assert.throws(()=>current(host,'finish',{index:1}),/stale/);
  action(guest,'skip',{round:2});
  action(host,'pick',{round:2,index:0});
  assert.equal(action(host,'pass',{round:2,index:0}).ready,true);
  now=4*3600*1000;
  assert.equal(action(host,'state'),null);
  assert.throws(()=>action(guest,'join'),/no_room/);
});
